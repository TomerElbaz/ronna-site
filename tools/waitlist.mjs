// The waitlist switch (CPO order TC-006). One flag, site.config.json's
// "waitlistOpen", decides what the join section of / and /what/ holds:
//   false: one plain line, "The list opens soon. Check back here." No email
//          field, no button, nothing posted anywhere.
//   true:  the real form (tools/waitlist/open.html), unchanged.
// Pages has no build step and serves public/ as committed, so the flag is
// applied here, before the commit:
//   node tools/waitlist.mjs           write public/ to match the flag
//   node tools/waitlist.mjs --check   exit 1 if public/ doesn't match it (npm test runs this)
// At go-live: set "waitlistOpen" to true, run `npm run waitlist`, commit. No hand edits.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PAGES = ["index.html", "what/index.html"];
const START = "<!-- waitlist:start (generated by tools/waitlist.mjs from site.config.json; edit tools/waitlist/*.html) -->\n";
const END = "        <!-- waitlist:end -->";
const BLOCK = /<!-- waitlist:start[^>]*-->\n[\s\S]*?<!-- waitlist:end -->/;

export function waitlistOpen(root = repo) {
  return JSON.parse(readFileSync(path.join(root, "site.config.json"), "utf8")).waitlistOpen === true;
}

export function render(html, open) {
  if (!BLOCK.test(html)) throw new Error("waitlist markers missing");
  const part = readFileSync(path.join(repo, "tools", "waitlist", open ? "open.html" : "closed.html"), "utf8");
  return html.replace(BLOCK, () => START + part + END);
}

// Writes the variant into `publicDir` (default: the repo's public/). Returns the pages that changed.
export function apply(open, publicDir = path.join(repo, "public")) {
  const changed = [];
  for (const p of PAGES) {
    const file = path.join(publicDir, p);
    const before = readFileSync(file, "utf8");
    const after = render(before, open);
    if (after !== before) {
      writeFileSync(file, after);
      changed.push(p);
    }
  }
  return changed;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const open = waitlistOpen();
  if (process.argv.includes("--check")) {
    const stale = PAGES.filter((p) => {
      const html = readFileSync(path.join(repo, "public", p), "utf8");
      return render(html, open) !== html;
    });
    if (stale.length) {
      console.log(`FAIL: public/${stale.join(", public/")} out of step with site.config.json (waitlistOpen: ${open}); run npm run waitlist`);
      process.exit(1);
    }
    console.log(`OK: waitlist ${open ? "open (the form)" : "closed (one line, no form)"} on / and /what/, as site.config.json says`);
  } else {
    const changed = apply(open);
    console.log(`waitlist ${open ? "open" : "closed"}: ${changed.length ? "updated " + changed.join(", ") : "no change"}`);
  }
}
