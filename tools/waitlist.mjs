// The waitlist switch (CPO orders TC-006 and 15 Oct). One flag, site.config.json's
// "waitlistOpen", decides what the list's pages hold: the join section of /
// and /what/, and the working part of /off/ and /invite/.
//   false: one plain line, "The list opens soon. Check back here." No field,
//          no button, nothing posted anywhere.
//   true:  the real forms (tools/waitlist/<block>.open.html), unchanged.
// Pages has no build step and serves public/ as committed, so the flag is
// applied here, before the commit:
//   node tools/waitlist.mjs           write public/ to match the flag
//   node tools/waitlist.mjs --check   exit 1 if public/ doesn't match it (npm test runs this)
// At go-live: set "waitlistOpen" to true, run `npm run waitlist`, commit. No hand edits.
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
// Page -> block. Each block has <block>.open.html and <block>.closed.html in tools/waitlist/.
export const BLOCKS = { "index.html": "join", "what/index.html": "join", "off/index.html": "off", "invite/index.html": "invite" };
export const PAGES = Object.keys(BLOCKS);
// Whole pages that exist only while the list is open (W-05(1)): copied from
// tools/waitlist/gated/ into public/ when open, removed from public/ when closed.
export const GATED = ["how-mom-works"];
const START = "<!-- waitlist:start (generated by tools/waitlist.mjs from site.config.json; edit tools/waitlist/*.html) -->\n";
const END = "        <!-- waitlist:end -->";
const BLOCK = /<!-- waitlist:start[^>]*-->\n[\s\S]*?<!-- waitlist:end -->/;

export function waitlistOpen(root = repo) {
  return JSON.parse(readFileSync(path.join(root, "site.config.json"), "utf8")).waitlistOpen === true;
}

export function render(html, open, block) {
  if (!BLOCK.test(html)) throw new Error("waitlist markers missing");
  const part = readFileSync(path.join(repo, "tools", "waitlist", `${block}.${open ? "open" : "closed"}.html`), "utf8");
  return html.replace(BLOCK, () => START + part + END);
}

// Writes the variant into `publicDir` (default: the repo's public/). Returns the pages that changed.
export function apply(open, publicDir = path.join(repo, "public")) {
  const changed = [];
  for (const g of GATED) {
    const dest = path.join(publicDir, g);
    if (open) {
      cpSync(path.join(repo, "tools", "waitlist", "gated", g), dest, { recursive: true });
      changed.push(g + "/");
    } else if (existsSync(dest)) {
      rmSync(dest, { recursive: true });
      changed.push(g + "/ (removed)");
    }
  }
  for (const p of PAGES) {
    const file = path.join(publicDir, p);
    const before = readFileSync(file, "utf8");
    const after = render(before, open, BLOCKS[p]);
    if (after !== before) {
      writeFileSync(file, after);
      changed.push(p);
    }
  }
  return changed;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const open = waitlistOpen();
  if (process.argv.includes("--check")) {
    const stale = PAGES.filter((p) => {
      const html = readFileSync(path.join(repo, "public", p), "utf8");
      return render(html, open, BLOCKS[p]) !== html;
    });
    for (const g of GATED) {
      const pub = path.join(repo, "public", g, "index.html");
      const src = path.join(repo, "tools", "waitlist", "gated", g, "index.html");
      if (open ? !existsSync(pub) || readFileSync(pub, "utf8") !== readFileSync(src, "utf8") : existsSync(path.join(repo, "public", g))) stale.push(g + "/");
    }
    if (stale.length) {
      console.log(`FAIL: public/${stale.join(", public/")} out of step with site.config.json (waitlistOpen: ${open}); run npm run waitlist`);
      process.exit(1);
    }
    console.log(`OK: waitlist ${open ? "open (the forms)" : "closed (one line, no form)"} on /, /what/, /off/ and /invite/, as site.config.json says`);
  } else {
    const changed = apply(open);
    console.log(`waitlist ${open ? "open" : "closed"}: ${changed.length ? "updated " + changed.join(", ") : "no change"}`);
  }
}
